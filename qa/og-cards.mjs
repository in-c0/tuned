// Renders the 1200×630 share cards in public/og/ and the handle list in src/og-cards.ts.
//
// Why a committed PNG rather than a card drawn per request: a Worker has no raster engine, and
// the only images this service owned before were a 512×512 icon, which is why every feed shared
// as a small `summary` card. These cards carry identity only — name, handle, agent label — and
// no item, count or age, so nothing in them can go stale or overstate freshness.
//
// Usage (from qa/, after `npm ci && npx playwright install chromium`):
//   node og-cards.mjs feeds.json
// feeds.json: [{ "handle": "ava", "name": "Ava Kim", "accent": "#7c6cff", "agent": false }, ...]
// Re-run when a feed is added or renamed; a handle with no card falls back to og/default.png.
import { chromium } from "@playwright/test";
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const feeds = JSON.parse(fs.readFileSync(process.argv[2], "utf8"));
const outDir = path.join(root, "public", "og");
fs.mkdirSync(outDir, { recursive: true });

const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]);
const shell = (inner) => `<!doctype html><html><head><meta charset="utf-8"><style>
  * { margin: 0; box-sizing: border-box; }
  body { width: 1200px; height: 630px; background: #0b0b10; color: #eceaf4;
    font-family: ui-sans-serif, system-ui, -apple-system, "Segoe UI", Roboto, "Noto Sans", sans-serif;
    padding: 64px 72px; display: flex; flex-direction: column; position: relative; overflow: hidden; }
  .glow { position: absolute; right: -180px; top: -180px; width: 640px; height: 640px; border-radius: 50%;
    background: radial-gradient(circle, var(--a) 0%, transparent 62%); opacity: .22; }
  .mark { font-size: 26px; letter-spacing: .16em; font-weight: 600; color: #9a98ad; }
  .mark b { color: #7c6cff; }
  .mid { flex: 1; display: flex; flex-direction: column; justify-content: center; gap: 22px; }
  .row { display: flex; align-items: center; gap: 28px; }
  .av { width: 120px; height: 120px; border-radius: 50%; flex: none; display: grid; place-items: center;
    font-size: 56px; font-weight: 700; background: linear-gradient(135deg, var(--a), #2b2b3d); }
  h1 { font-size: 64px; line-height: 1.06; letter-spacing: -.02em; font-weight: 700; max-width: 18ch; }
  .sub { font-size: 34px; color: #9a98ad; }
  .badge { display: inline-block; font-size: 20px; font-weight: 700; letter-spacing: .08em; padding: 6px 14px;
    border-radius: 999px; background: linear-gradient(90deg, #4cc9f0, #7c6cff); color: #0b0b10; vertical-align: middle; }
  .foot { font-size: 24px; color: #6f6d82; display: flex; justify-content: space-between; }
  .accent { color: #7c6cff; }
</style></head><body>${inner}</body></html>`;

const feedCard = (f) => shell(`<div class="glow" style="--a:${esc(f.accent)}"></div>
  <div class="mark"><b>·</b> tuned</div>
  <div class="mid" style="--a:${esc(f.accent)}">
    <div class="row"><div class="av">${esc(f.name.slice(0, 1).toUpperCase())}</div>
      <div>${f.agent ? `<span class="badge">AI AGENT</span>` : ""}</div></div>
    <h1>${esc(f.name)}</h1>
    <div class="sub">what <span class="accent">@${esc(f.handle)}</span> is paying attention to</div>
  </div>
  <div class="foot"><span>Follow attention, not content</span><span>justtuned.com/${esc(f.handle)}</span></div>`);

const defaultCard = shell(`<div class="glow" style="--a:#7c6cff"></div>
  <div class="mark"><b>·</b> tuned</div>
  <div class="mid"><h1 style="font-size:84px;max-width:14ch">Follow what people <span class="accent">pay attention to</span>.</h1>
    <div class="sub">Real feeds of what people and their AI agents read, watch and listen to.</div></div>
  <div class="foot"><span>No posts, no captions</span><span>justtuned.com</span></div>`);

const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1200, height: 630 } });
const shoot = async (html, file) => { await page.setContent(html); await page.screenshot({ path: path.join(outDir, file) }); };
await shoot(defaultCard, "default.png");
for (const f of feeds) {
  if (!/^[a-z0-9][a-z0-9-]{1,30}$/.test(f.handle)) throw new Error(`bad handle: ${f.handle}`);
  await shoot(feedCard(f), `${f.handle}.png`);
}
await browser.close();

const handles = feeds.map((f) => f.handle).sort();
fs.writeFileSync(path.join(root, "src", "og-cards.ts"), `// Generated by qa/og-cards.mjs — the handles that have a share card in public/og/.
// Regenerate rather than edit; a handle missing here falls back to /og/default.png.
export const OG_CARD_HANDLES: ReadonlySet<string> = new Set(${JSON.stringify(handles)});
`);
console.log(`wrote default.png + ${handles.length} feed cards`);
